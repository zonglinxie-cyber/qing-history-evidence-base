import fs from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

// 读图片头拿像素尺寸。只解析文件头，不解码整张图——全库 800 个文件要秒级跑完。
// 支持 JPEG（SOF 段）、PNG（IHDR）、WebP（VP8/VP8L/VP8X）。
export function imageSize(buf) {
  if (buf.length > 24 && buf[0] === 0x89 && buf.toString('latin1', 1, 4) === 'PNG') {
    return { w: buf.readUInt32BE(16), h: buf.readUInt32BE(20) };
  }
  if (buf.length > 30 && buf.toString('latin1', 0, 4) === 'RIFF' && buf.toString('latin1', 8, 12) === 'WEBP') {
    const type = buf.toString('latin1', 12, 16);
    if (type === 'VP8X') {
      return {
        w: 1 + (buf[24] | (buf[25] << 8) | (buf[26] << 16)),
        h: 1 + (buf[27] | (buf[28] << 8) | (buf[29] << 16)),
      };
    }
    if (type === 'VP8 ') return { w: buf.readUInt16LE(26) & 0x3fff, h: buf.readUInt16LE(28) & 0x3fff };
    if (type === 'VP8L') {
      const bits = buf.readUInt32LE(21);
      return { w: (bits & 0x3fff) + 1, h: ((bits >> 14) & 0x3fff) + 1 };
    }
  }
  if (buf.length > 4 && buf[0] === 0xff && buf[1] === 0xd8) {
    let i = 2;
    while (i + 9 < buf.length) {
      if (buf[i] !== 0xff) { i++; continue; }
      const marker = buf[i + 1];
      if (marker >= 0xc0 && marker <= 0xcf && marker !== 0xc4 && marker !== 0xc8 && marker !== 0xcc) {
        return { h: buf.readUInt16BE(i + 5), w: buf.readUInt16BE(i + 7) };
      }
      if (marker === 0xd8 || marker === 0x01 || (marker >= 0xd0 && marker <= 0xd7)) { i += 2; continue; }
      i += 2 + buf.readUInt16BE(i + 2);
    }
  }
  return null;
}

// 变体档（-480 / -960 / @2x）与主图同比例，只需主图一条。
export function isVariant(name) {
  return /-(?:480|960)\.|@2x\./i.test(name);
}

// 同一张图的各档（主图 + -480 / -960 / @2x）共用一个 stem。
// 与 site/templates.js 里 mediaSrcset() 的取 stem 规则必须一致。
export function stemOf(name) {
  const m = name.match(/^(.*?)(?:-(?:480|960)|@2x)?\.[A-Za-z0-9]+$/);
  return 'media/' + (m ? m[1] : name);
}

// Only advertise image variants that are actually shipped with this site.
export function buildMediaManifest() {
  const mediaDir = new URL('../site/media/', import.meta.url);
  const files = fs.readdirSync(mediaDir).filter(name => /\.(?:jpe?g|png|webp)$/i.test(name)).sort();

  // 画廊取景要按图片自身的宽高比分档（竖幅人物裁成 4:3 会把脸切掉，长卷裁成 4:3 只剩一小段），
  // 而渲染在浏览器里、拿不到文件尺寸，所以在构建期算好随清单一起发出去。见 site/styles.css 的 .visual-pic。
  const aspect = {};
  // 内容指纹：图片「文件名不变、内容会换」（帝容换源、重新切档都是这样），
  // 只靠文件名做不了缓存失效。所以把每个 stem 的内容指纹一起发出去，
  // 由 mediaSrcset() 拼成 `?v=……`——图片一变，URL 就变，浏览器必然重取。
  const hashers = new Map();
  for (const name of files) {
    const buf = fs.readFileSync(new URL(name, mediaDir));
    const stem = stemOf(name);
    const h = hashers.get(stem) || createHash('sha1');
    h.update(name).update(buf);
    hashers.set(stem, h);
    if (isVariant(name)) continue;
    const size = imageSize(buf);
    if (!size || !size.w || !size.h) continue;
    aspect['media/' + name] = Math.round((size.w / size.h) * 100) / 100;
  }
  const stemVer = {};
  for (const [stem, h] of hashers) stemVer[stem] = h.digest('hex').slice(0, 8);

  const output = [
    '// Generated by scripts/build-media-manifest.mjs',
    `export const MEDIA_FILES = new Set(${JSON.stringify(files.map(name => 'media/' + name))});`,
    '// 主图宽高比（宽 ÷ 高，两位小数）。只列主图：预览文件一律指向主图，变体档与主图同比例。',
    `export const MEDIA_ASPECT = ${JSON.stringify(aspect)};`,
    '// stem → 内容指纹（8 位）。主图与其 -480 / -960 / @2x 共用一条，用于 ?v= 缓存失效。',
    `export const MEDIA_STEM_VER = ${JSON.stringify(stemVer)};`,
    '',
  ].join('\n');

  const dest = new URL('../site/media-manifest.js', import.meta.url);
  if (!fs.existsSync(dest) || fs.readFileSync(dest, 'utf8') !== output) fs.writeFileSync(dest, output);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) buildMediaManifest();
